# A plugin may be enabled for every machine only when its scope is the user, not
# a project: memory that follows you across repos, or a behavioral disposition
# about how you want code written. Capability -- tools, MCP servers, domain
# knowledge -- stays with the project that needs it, via that project's APM
# manifest. Adding to this set means arguing the plugin carries no capability.
USER_SCOPED_PLUGINS = {
    "memsearch@memsearch-plugins",  # memory: your history, every repo
    "ponytail@ponytail",  # disposition: prefer the simplest thing that works
}


def test_home_claude_global_plugins_are_user_scoped_only():
    settings = sorted((ROOT / "home/.claude").glob("settings.*.json"))
    for path in settings:
        enabled = {
            name
            for name, value in json.loads(path.read_text())
            .get("enabledPlugins", {})
            .items()
            if value
        }
        assert enabled <= USER_SCOPED_PLUGINS, path
    shared = json.loads((ROOT / "home/.claude/settings.shared.json").read_text())
    assert {
        name for name, value in shared["enabledPlugins"].items() if value
    } == USER_SCOPED_PLUGINS


def test_install_removes_retired_toolkit_symlinks(tmp_path):
    stale = (
        tmp_path / ".agents/mcp-registry.json",
        tmp_path / ".claude/hooks",
    )
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.symlink_to(ROOT / "home" / path.relative_to(tmp_path))

    result = subprocess.run(
        [
            ROOT / "bin/dotagents",
            "install",
            "--no-pull",
            "--profile",
            "vps",
        ],
        env={**os.environ, "HOME": str(tmp_path)},
        text=True,
        capture_output=True,
    )

    assert result.returncode == 0, result.stdout + result.stderr
    for path in stale:
        assert not path.is_symlink(), path


def test_install_removes_marker_owned_toolkit_project_residue(tmp_path):
    repo = tmp_path / "repo"
    (repo / "bin").mkdir(parents=True)
    shutil.copy2(ROOT / "bin/dotagents", repo / "bin/dotagents")
    shutil.copytree(ROOT / "home", repo / "home")
    (repo / ".git/info").mkdir(parents=True)
    exclude = repo / ".git/info/exclude"
    exclude.write_text(
        "keep-me\n"
        ".mcp.json\n"
        ".claude/.toolkit-stamp\n"
        ".codex/\n"
        "/.codex/\n"
        ".claude/skills/\n"
        ".claude/settings.local.json\n"
    )
    codex_config = repo / ".codex/config.toml"
    codex_config.parent.mkdir()
    codex_config.write_text(
        "# generated by dotagents toolkit hook\n\n"
        "[mcp_servers.perplexity]\n"
    )
    home = tmp_path / "home"
    home.mkdir()

    dry_run = subprocess.run(
        [
            repo / "bin/dotagents",
            "install",
            "--no-pull",
            "--dry-run",
            "--profile",
            "vps",
        ],
        env={**os.environ, "HOME": str(home)},
        text=True,
        capture_output=True,
    )
    assert dry_run.returncode == 0, dry_run.stdout + dry_run.stderr
    assert codex_config.exists()
    assert ".codex/" in exclude.read_text()

    result = subprocess.run(
        [
            repo / "bin/dotagents",
            "install",
            "--no-pull",
            "--profile",
            "vps",
        ],
        env={**os.environ, "HOME": str(home)},
        text=True,
        capture_output=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert not codex_config.exists()
    assert exclude.read_text() == "keep-me\n"


