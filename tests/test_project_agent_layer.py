def test_agent_sync_leaves_home_tree_byte_identical():
    before = tree_digest(ROOT / "home")
    subprocess.run(
        ["mise", "run", "agent-sync"],
        cwd=ROOT,
        check=True,
    )
    assert tree_digest(ROOT / "home") == before


